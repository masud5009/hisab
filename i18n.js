const LANG_KEY = "hisab_lang";

export function getLanguage() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "bn" || saved === "en") return saved;
  return "bn"; // Default to Bengali for local mess users
}

export function setLanguage(lang) {
  if (lang !== "bn" && lang !== "en") return;
  localStorage.setItem(LANG_KEY, lang);
  applyTranslations();
}

export function toggleLanguage() {
  const current = getLanguage();
  const next = current === "bn" ? "en" : "bn";
  setLanguage(next);
  return next;
}

export function t(key) {
  const lang = getLanguage();
  return translations[lang]?.[key] || translations["en"]?.[key] || key;
}

export function applyTranslations(root = document) {
  const lang = getLanguage();
  const dict = translations[lang] || translations["en"];
  
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      if (el.tagName === "INPUT" && (el.type === "button" || el.type === "submit")) {
        el.value = dict[key];
      } else if (el.hasAttribute("placeholder")) {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Update language toggle button indicator if exists
  const langBtnLabel = root.getElementById("currentLangLabel");
  if (langBtnLabel) {
    langBtnLabel.textContent = dict.lang_toggle_label;
  }
}
